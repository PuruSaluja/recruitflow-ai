"""Write a synthetic labelled corpus to disk.

The corpus itself is generated by ``app.ml.corpus``; this script is the command
line around it. Output is four files in ``--out``:

* ``jobs.jsonl`` -- one requisition per line.
* ``candidates.jsonl`` -- one candidate per line, including the demographics
  and true skills that ``api_payload`` deliberately withholds. The fairness
  audit needs them; the matcher must never read them.
* ``pairs.jsonl`` -- one labelled job/candidate pair per line.
* ``manifest.json`` -- the config used, the measured summary, and the
  interpreter that produced it.

The corpus is reproducible from its seed on one interpreter, but ``random``'s
sampling is not guaranteed to draw the same across Python versions, which is
why the manifest records the version rather than assuming it. The files are
not committed -- regenerate them with this script.

    python data/generate_corpus.py --out data/corpus
"""

from __future__ import annotations

import argparse
import dataclasses
import json
import platform
import sys
from collections.abc import Iterable
from pathlib import Path
from typing import Any

from app.ml.corpus import Corpus, CorpusConfig, corpus_summary, generate_corpus

DEFAULT_OUT = Path(__file__).resolve().parent / "corpus"


def build_parser() -> argparse.ArgumentParser:
    defaults = CorpusConfig()
    parser = argparse.ArgumentParser(
        prog="generate_corpus",
        description="Generate a synthetic labelled recruiting corpus and write it out.",
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=DEFAULT_OUT,
        help="directory to write into, created if missing (default: %(default)s)",
    )
    parser.add_argument("--seed", type=int, default=defaults.seed)
    parser.add_argument("--jobs", type=int, default=defaults.n_jobs, dest="n_jobs")
    parser.add_argument(
        "--candidates", type=int, default=defaults.n_candidates, dest="n_candidates"
    )
    parser.add_argument("--slate-size", type=int, default=defaults.slate_size)
    parser.add_argument("--same-family-share", type=float, default=defaults.same_family_share)
    parser.add_argument(
        "--historical-bias",
        type=float,
        default=defaults.historical_bias,
        help="how much less often women were advanced; 0 removes the planted bias",
    )
    parser.add_argument(
        "--proxy-share",
        type=float,
        default=defaults.proxy_share,
        help="share of women's community lines naming a women-in-tech group; 0 removes the proxy",
    )
    return parser


def config_from(args: argparse.Namespace) -> CorpusConfig:
    fields = {field.name for field in dataclasses.fields(CorpusConfig)}
    return CorpusConfig(**{key: value for key, value in vars(args).items() if key in fields})


def record(item: Any) -> dict[str, Any]:
    """One corpus row as JSON-ready data, with sets ordered so output is stable."""
    row = {}
    for field in dataclasses.fields(item):
        value = getattr(item, field.name)
        row[field.name] = sorted(value) if isinstance(value, frozenset) else value
    return row


def write_jsonl(path: Path, items: Iterable[Any]) -> int:
    count = 0
    with path.open("w", encoding="utf-8", newline="\n") as handle:
        for item in items:
            handle.write(json.dumps(record(item), ensure_ascii=False) + "\n")
            count += 1
    return count


def write_corpus(corpus: Corpus, out: Path) -> dict[str, Any]:
    """Write the four files and return the manifest that was written."""
    out.mkdir(parents=True, exist_ok=True)
    counts = {
        "jobs.jsonl": write_jsonl(out / "jobs.jsonl", corpus.jobs),
        "candidates.jsonl": write_jsonl(out / "candidates.jsonl", corpus.candidates),
        "pairs.jsonl": write_jsonl(out / "pairs.jsonl", corpus.pairs),
    }
    manifest = {
        "synthetic": True,
        "generator": "app.ml.corpus.generate_corpus",
        "config": dataclasses.asdict(corpus.config),
        "rows": counts,
        "summary": dataclasses.asdict(corpus_summary(corpus)),
        # random's sampling is not guaranteed to draw the same across versions,
        # so a seed reproduces this corpus only on the interpreter named here.
        "python": platform.python_version(),
        "implementation": platform.python_implementation(),
    }
    (out / "manifest.json").write_text(
        json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n"
    )
    return manifest


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    try:
        config = config_from(args)
        corpus = generate_corpus(config)
    except ValueError as error:
        # The config rules and the slate-pool check both raise this; the caller
        # asked for a corpus that cannot exist, which is not a crash.
        print(f"error: {error}", file=sys.stderr)
        return 2

    manifest = write_corpus(corpus, args.out)
    summary = manifest["summary"]
    print(f"Wrote {args.out}")
    for name, count in manifest["rows"].items():
        print(f"  {name}: {count} rows")
    print(f"  relevance 0/1/2: {'/'.join(str(summary['relevance_counts'][g]) for g in (0, 1, 2))}")
    print(f"  median relevant per job: {summary['median_relevant_per_job']:g}")
    print(f"  jobs with nobody strong: {summary['jobs_without_strong']}")
    print(f"  advance rate: {summary['advance_rate']:.1%}")
    ratio = summary["women_to_men_advance_ratio"]
    print(f"  women-to-men advance ratio: {'n/a' if ratio is None else f'{ratio:.3f}'}")
    print(f"  women's resumes naming a women-in-tech group: {summary['proxy_rate_women']:.1%}")
    print(f"  python: {manifest['implementation']} {manifest['python']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
